# ─── Main Execution ───────────────────────────────────────────────────────────

def run_audit(csv_path_override: Optional[str] = None) -> int:
    print("=" * 70)
    print("STEP 9.4 — LIVE DIAGNOSTIC LOG ANALYSIS: INDEPENDENT AUDIT")
    print("=" * 70)

    # 1. Pre-hash critical artifacts
    print("\n[1/5] Hashing critical artifacts pre-audit...")
    artifact_pre = hash_critical_artifacts(CRITICAL_ARTIFACTS)
    for p, (sz, h) in artifact_pre.items():
        print(f"  {os.path.basename(p)}: size={sz}, sha={h[:12] if h else 'N/A'}...")

    # 2. Locate diagnostic CSV
    print("\n[2/5] Locating live diagnostic CSV session...")
    csv_path = csv_path_override or find_latest_diagnostic_csv(DEFAULT_DIAG_DIR)

    rows: List[Dict[str, Any]] = []
    validation_errors: List[str] = []
    validation_metrics: Dict[str, Any] = {}
    trials: List[TrialRecord] = []

    if csv_path is None or not os.path.exists(csv_path):
        print(f"  [MISSING] No diagnostic CSV found under '{DEFAULT_DIAG_DIR}'.")
        print("  Root cause: app.py was executed in default production mode without --diagnostics.")
        print("  Audit status: BLOCKED (Prerequisite missing).")
    else:
        print(f"  [FOUND] Located CSV: {csv_path} ({os.path.getsize(csv_path)} bytes)")

        # 3. Parse and validate CSV
        print("\n[3/5] Parsing CSV and validating schema & data types...")
        rows, validation_errors, validation_metrics = parse_and_validate_csv(csv_path)
        print(f"  Total records parsed: {validation_metrics['total_rows']}")
        print(f"  Camera read ok: {validation_metrics['camera_read_ok_count']}, failed: {validation_metrics['camera_read_fail_count']}")
        print(f"  Hand detected: {validation_metrics['hand_detected_count']}, norm success: {validation_metrics['norm_success_count']}")
        print(f"  Commit events: {validation_metrics['commit_event_count']}")

        if validation_errors:
            print(f"  [WARN] Encountered {len(validation_errors)} schema/validation errors:")
            for err in validation_errors[:5]:
                print(f"     - {err}")

        # 4. Segment clusters & analyze trials
        print("\n[4/5] Segmenting hand clusters & evaluating 33 intended trials...")
        clusters = segment_hand_clusters(rows)
        print(f"  Identified {len(clusters)} distinct gesture clusters.")

        # Map clusters to the 33 intended trials
        for idx in range(min(len(clusters), TOTAL_INTENDED_TRIALS)):
            target_idx = idx // TRIALS_PER_LETTER
            intended = TARGET_LETTERS[target_idx] if target_idx < len(TARGET_LETTERS) else "?"
            t_record = analyze_trial(idx + 1, intended, clusters[idx])
            trials.append(t_record)
            print(f"  Trial {idx+1:02d} [{intended}]: {t_record.match_status} | {t_record.failure_stage} | Top: {t_record.top_predicted_label} | Conf: {t_record.conf_mean:.2f} | Commit: {t_record.committed_letter}")

    # 5. Post-hash critical artifacts
    print("\n[5/5] Checking post-audit artifact integrity...")
    artifact_post = hash_critical_artifacts(CRITICAL_ARTIFACTS)
    integrity_ok = True
    for p in CRITICAL_ARTIFACTS:
        pre_sz, pre_h = artifact_pre[p]
        post_sz, post_h = artifact_post[p]
        if pre_sz != post_sz or pre_h != post_h:
            integrity_ok = False
            print(f"  [MUTATION DETECTED]: {os.path.basename(p)}")
        else:
            print(f"  [OK] {os.path.basename(p)}: unchanged")

    # Generate Report
    report = build_audit_report(
        csv_path=csv_path,
        rows=rows,
        validation_errors=validation_errors,
        validation_metrics=validation_metrics,
        trials=trials,
        artifact_pre=artifact_pre,
        artifact_post=artifact_post,
    )

    os.makedirs(os.path.dirname(os.path.abspath(REPORT_PATH)), exist_ok=True)
    with open(REPORT_PATH, "w", encoding="utf-8") as f:
        f.write(report)

    print(f"\nAudit Report written to: {REPORT_PATH}")

    if csv_path is None or not os.path.exists(csv_path):
        print("Overall Audit Result: BLOCKED (Missing live diagnostic CSV prerequisite)")
        return 2
    elif validation_errors or not integrity_ok:
        print("Overall Audit Result: FAIL")
        return 1
    else:
        print("Overall Audit Result: PASS")
        return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Audit live diagnostic logs")
    parser.add_argument("--csv", type=str, default=None, help="Path to diagnostic CSV (default: newest in reports/live_diagnostics)")
    args = parser.parse_args()
    sys.exit(run_audit(csv_path_override=args.csv))
