# ─── SHA-256 Integrity Helpers ────────────────────────────────────────────────

def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def hash_critical_artifacts(paths: List[str]) -> Dict[str, Tuple[Optional[int], Optional[str]]]:
    out = {}
    for p in paths:
        if os.path.exists(p):
            out[p] = (os.path.getsize(p), sha256_file(p))
        else:
            out[p] = (None, None)
    return out


